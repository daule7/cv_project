def img(path, width=W, cap=None):
    from PIL import Image as PI
    im = PI.open(path)
    h = width * im.height / im.width
    out = [Image(str(path), width=width, height=h)]
    if cap:
        out.append(P(cap, "cap"))
    return KeepTogether(out)


def table(rows, widths=None, header=True, zebra=True, align_right_from=1):
    data = [[c if not isinstance(c, str) else Paragraph(c, ST["cellb" if (header and i == 0)
                                                               else "cell"])
             for c in r] for i, r in enumerate(rows)]
    t = Table(data, colWidths=widths, repeatRows=1 if header else 0)
    sty = [("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
           ("LINEBELOW", (0, 0), (-1, 0), 0.8, INK2),
           ("LINEBELOW", (0, -1), (-1, -1), 0.5, RULE),
           ("TOPPADDING", (0, 0), (-1, -1), 2.5), ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
           ("LEFTPADDING", (0, 0), (-1, -1), 4), ("RIGHTPADDING", (0, 0), (-1, -1), 4)]
    if zebra:
        for i in range(1, len(rows)):
            if i % 2 == 0:
                sty.append(("BACKGROUND", (0, i), (-1, i), BG))
    t.setStyle(TableStyle(sty))
    return t


def code(src, max_lines=None):
    src = textwrap.dedent(src).rstrip()
    lines = src.split("\n")
    if max_lines and len(lines) > max_lines:
        lines = lines[:max_lines] + ["    ..."]
    lines = [l if len(l) <= 104 else l[:101] + "..." for l in lines]
    return Preformatted("\n".join(lines), ST["code"])


def src_of(fn, drop_doc=True, max_lines=None):
    s = inspect.getsource(fn)
    if drop_doc:
        s = re.sub(r'(\n\s+)"""[\s\S]*?"""\n', "\n", s, count=1)
    return code(s, max_lines)


